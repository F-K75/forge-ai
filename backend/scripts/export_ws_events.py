"""Generate frontend/src/lib/generated/{wsEvents,pmWsEvents}.ts from the
backend's WSEventType / PMWSEventType enums.

These enums are the single source of truth for WebSocket event names. Run
this whenever either enum changes so the frontend contract can't drift out
of sync with what the backend actually emits.
"""
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = BACKEND_DIR.parent
GENERATED_DIR = REPO_ROOT / "frontend" / "src" / "lib" / "generated"

sys.path.insert(0, str(BACKEND_DIR))

from core.models import WSEventType  # noqa: E402
from core.pm_models import PMWSEventType  # noqa: E402


def _write(output_path: Path, const_name: str, enum_cls) -> None:
    members = [member.value for member in enum_cls]
    entries = "\n".join(f'  {value}: "{value}",' for value in members)

    contents = (
        "// AUTO-GENERATED by backend/scripts/export_ws_events.py — do not edit by hand.\n"
        "// Regenerate with: python backend/scripts/export_ws_events.py\n"
        f"export const {const_name} = {{\n"
        f"{entries}\n"
        "} as const\n"
    )

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(contents)
    print(f"Wrote {len(members)} event types to {output_path}")


def main() -> None:
    _write(GENERATED_DIR / "wsEvents.ts", "WS_EVENT_TYPES", WSEventType)
    _write(GENERATED_DIR / "pmWsEvents.ts", "PM_WS_EVENT_TYPES", PMWSEventType)


if __name__ == "__main__":
    main()
