"""Generate frontend/src/lib/generated/wsEvents.ts from core.models.WSEventType.

WSEventType is the single source of truth for WebSocket event names. Run this
whenever the enum changes so the frontend contract can't drift out of sync
with what the backend actually emits.
"""
import sys
from pathlib import Path

BACKEND_DIR = Path(__file__).resolve().parent.parent
REPO_ROOT = BACKEND_DIR.parent
OUTPUT_PATH = REPO_ROOT / "frontend" / "src" / "lib" / "generated" / "wsEvents.ts"

sys.path.insert(0, str(BACKEND_DIR))

from core.models import WSEventType  # noqa: E402


def main() -> None:
    members = [member.value for member in WSEventType]
    entries = "\n".join(f'  {value}: "{value}",' for value in members)

    contents = (
        "// AUTO-GENERATED by backend/scripts/export_ws_events.py — do not edit by hand.\n"
        "// Regenerate with: python backend/scripts/export_ws_events.py\n"
        "export const WS_EVENT_TYPES = {\n"
        f"{entries}\n"
        "} as const\n"
    )

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(contents)
    print(f"Wrote {len(members)} event types to {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
